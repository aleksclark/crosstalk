// Shared Tailwind v3 preset for CrossTalk SPAs. Maps semantic color names to
// the CSS custom properties defined in theme.css so `bg-card`, `border-border`,
// `text-muted-foreground`, etc. resolve to the shared dark palette.
//
// Usage (tailwind.config.{js,ts}):
//   import themePreset from "@crosstalk/theme/preset";
//   export default { presets: [themePreset], content: [...] };

/** @type {Partial<import('tailwindcss').Config>} */
const preset = {
  darkMode: "class",
  theme: {
    extend: {
      colors: {
        border: "hsl(var(--border))",
        input: "hsl(var(--input))",
        ring: "hsl(var(--ring))",
        background: "hsl(var(--background))",
        foreground: "hsl(var(--foreground))",
        card: "hsl(var(--card))",
        "card-foreground": "hsl(var(--card-foreground))",
        primary: "hsl(var(--primary))",
        "primary-foreground": "hsl(var(--primary-foreground))",
        muted: "hsl(var(--muted))",
        "muted-foreground": "hsl(var(--muted-foreground))",
        accent: "hsl(var(--accent))",
        "accent-foreground": "hsl(var(--accent-foreground))",
        destructive: "hsl(var(--destructive))",
        "destructive-foreground": "hsl(var(--destructive-foreground))",
      },
      borderRadius: {
        lg: "var(--radius)",
        md: "calc(var(--radius) - 2px)",
        sm: "calc(var(--radius) - 4px)",
      },
    },
  },
};

export default preset;
